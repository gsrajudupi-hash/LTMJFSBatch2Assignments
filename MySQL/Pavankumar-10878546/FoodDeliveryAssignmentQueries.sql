-- 1. Display all registered customers
SELECT customer_id, full_name, email, phone, is_active, created_at
FROM customers
ORDER BY customer_id;

-- 2. Display all active restaurants
SELECT restaurant_id, name, address, city, opening_time, closing_time, avg_rating
FROM restaurants
WHERE is_active = TRUE
ORDER BY name;

-- 3. Find all vegetarian food items
SELECT item_id, restaurant_id, category_id, name, description, price, is_available
FROM menu_items
WHERE is_veg = TRUE
ORDER BY name;

-- 4. Display food items belonging to a particular restaurant (replace ? with restaurant_id)
SELECT m.item_id, m.name AS item_name, c.name AS category_name, m.price, m.is_veg, m.is_available
FROM menu_items m
JOIN food_categories c ON m.category_id = c.category_id
WHERE m.restaurant_id = ?
ORDER BY c.name, m.name;

-- 5. Find food items whose price is greater than 200
SELECT item_id, restaurant_id, name, price, is_veg, is_available
FROM menu_items
WHERE price > 200.00
ORDER BY price DESC;

-- 6. Display all orders placed by a particular customer (replace ? with customer_id)
SELECT order_id, restaurant_id, order_date, subtotal, delivery_fee, discount_amount, final_amount, order_status
FROM orders
WHERE customer_id = ?
ORDER BY order_date DESC;

-- 7. Find all orders placed on a particular date (replace ? with 'YYYY-MM-DD')
SELECT order_id, customer_id, restaurant_id, order_date, final_amount, order_status
FROM orders
WHERE DATE(order_date) = ?
ORDER BY order_date;

-- 8. Display all available delivery partners
SELECT partner_id, full_name, phone, vehicle_type, vehicle_number
FROM delivery_partners
WHERE is_available = TRUE
ORDER BY full_name;

-- 9. Display customer details along with their delivery addresses
SELECT c.customer_id, c.full_name, c.email, c.phone,
       ca.address_id, ca.address_line, ca.city, ca.state, ca.pincode, ca.is_default
FROM customers c
LEFT JOIN customer_addresses ca ON c.customer_id = ca.customer_id
ORDER BY c.customer_id, ca.is_default DESC, ca.address_id;

-- 10. Display restaurant names along with their food menu
SELECT r.restaurant_id, r.name AS restaurant_name,
       c.name AS category_name, m.item_id, m.name AS item_name,
       m.price, m.is_veg, m.is_available
FROM restaurants r
LEFT JOIN menu_items m ON r.restaurant_id = m.restaurant_id
LEFT JOIN food_categories c ON m.category_id = c.category_id
ORDER BY r.name, c.name, m.name;

-- 11. Display complete order details, including customer and restaurant information
SELECT o.order_id, o.order_date, o.order_status,
       c.customer_id, c.full_name AS customer_name, c.phone AS customer_phone,
       r.restaurant_id, r.name AS restaurant_name,
       ca.address_line, ca.city,
       o.subtotal, o.delivery_fee, o.discount_amount, o.final_amount
FROM orders o
JOIN customers c ON o.customer_id = c.customer_id
JOIN restaurants r ON o.restaurant_id = r.restaurant_id
LEFT JOIN customer_addresses ca ON o.address_id = ca.address_id
ORDER BY o.order_date DESC;

-- 12. Find the total number of orders placed by each customer
SELECT c.customer_id, c.full_name, COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.full_name
ORDER BY total_orders DESC, c.full_name;

-- 13. Find the total number of food items available in each restaurant
SELECT r.restaurant_id, r.name AS restaurant_name,
       COUNT(m.item_id) AS available_items_count
FROM restaurants r
LEFT JOIN menu_items m
       ON r.restaurant_id = m.restaurant_id AND m.is_available = TRUE
GROUP BY r.restaurant_id, r.name
ORDER BY available_items_count DESC, r.name;

-- 14. Calculate the total sales generated by each restaurant (excluding cancelled orders)
SELECT r.restaurant_id, r.name AS restaurant_name,
       COALESCE(SUM(o.final_amount), 0.00) AS total_sales
FROM restaurants r
LEFT JOIN orders o
       ON r.restaurant_id = o.restaurant_id AND o.order_status <> 'CANCELLED'
GROUP BY r.restaurant_id, r.name
ORDER BY total_sales DESC;

-- 15. Find the most frequently ordered food item
SELECT m.item_id, m.name AS item_name, r.name AS restaurant_name,
       SUM(oi.quantity) AS total_quantity_ordered
FROM order_items oi
JOIN menu_items m ON oi.item_id = m.item_id
JOIN restaurants r ON m.restaurant_id = r.restaurant_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.order_status <> 'CANCELLED'
GROUP BY m.item_id, m.name, r.name
ORDER BY total_quantity_ordered DESC
LIMIT 1;

-- 16. Find customers who have never placed an order
SELECT c.customer_id, c.full_name, c.email, c.phone
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL
ORDER BY c.customer_id;

-- 17. Display delivery partners who have completed more than five deliveries
SELECT dp.partner_id, dp.full_name, dp.phone,
       COUNT(d.delivery_id) AS completed_deliveries
FROM delivery_partners dp
JOIN deliveries d ON dp.partner_id = d.partner_id
WHERE d.delivery_status = 'DELIVERED'
GROUP BY dp.partner_id, dp.full_name, dp.phone
HAVING COUNT(d.delivery_id) > 5
ORDER BY completed_deliveries DESC;

-- 18. Find the average rating of each restaurant
SELECT r.restaurant_id, r.name AS restaurant_name,
       ROUND(AVG(rev.rating), 2) AS avg_rating,
       COUNT(rev.review_id) AS total_reviews
FROM restaurants r
LEFT JOIN reviews rev ON r.restaurant_id = rev.restaurant_id
GROUP BY r.restaurant_id, r.name
ORDER BY avg_rating DESC, r.name;

-- 19. Find the customer who has spent the highest amount on food orders
SELECT c.customer_id, c.full_name, c.email,
       SUM(o.final_amount) AS total_spent
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
WHERE o.order_status <> 'CANCELLED'
GROUP BY c.customer_id, c.full_name, c.email
ORDER BY total_spent DESC
LIMIT 1;

-- 20. Find the restaurant that generated the highest revenue
SELECT r.restaurant_id, r.name AS restaurant_name,
       SUM(o.final_amount) AS total_revenue
FROM restaurants r
JOIN orders o ON r.restaurant_id = o.restaurant_id
WHERE o.order_status <> 'CANCELLED'
GROUP BY r.restaurant_id, r.name
ORDER BY total_revenue DESC
LIMIT 1;

-- 21. Find the second most expensive food item
WITH ranked_items AS (
    SELECT item_id, restaurant_id, name, price,
           DENSE_RANK() OVER (ORDER BY price DESC) AS price_rank
    FROM menu_items
)
SELECT item_id, restaurant_id, name, price
FROM ranked_items
WHERE price_rank = 2;

-- 22. Find restaurants whose average ratings are greater than the overall average rating
WITH restaurant_ratings AS (
    SELECT r.restaurant_id, r.name AS restaurant_name,
           AVG(rev.rating) AS avg_rating
    FROM restaurants r
    JOIN reviews rev ON r.restaurant_id = rev.restaurant_id
    GROUP BY r.restaurant_id, r.name
)
SELECT restaurant_id, restaurant_name, ROUND(avg_rating, 2) AS avg_rating
FROM restaurant_ratings
WHERE avg_rating > (SELECT AVG(rating) FROM reviews)
ORDER BY avg_rating DESC;

-- 23. Find customers who have placed more orders than the average number of orders per customer
WITH customer_order_counts AS (
    SELECT c.customer_id, c.full_name, COUNT(o.order_id) AS order_count
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.full_name
)
SELECT customer_id, full_name, order_count
FROM customer_order_counts
WHERE order_count > (SELECT AVG(order_count) FROM customer_order_counts)
ORDER BY order_count DESC;

-- 24. Find food items that have never been ordered
SELECT m.item_id, m.name AS item_name, r.name AS restaurant_name, m.price
FROM menu_items m
JOIN restaurants r ON m.restaurant_id = r.restaurant_id
LEFT JOIN order_items oi ON m.item_id = oi.item_id
WHERE oi.order_item_id IS NULL
ORDER BY r.name, m.name;

-- 25. Find the top three best-selling food items (by quantity sold)
WITH item_sales AS (
    SELECT m.item_id, m.name AS item_name, r.name AS restaurant_name,
           SUM(oi.quantity) AS units_sold,
           DENSE_RANK() OVER (ORDER BY SUM(oi.quantity) DESC) AS sales_rank
    FROM order_items oi
    JOIN menu_items m ON oi.item_id = m.item_id
    JOIN restaurants r ON m.restaurant_id = r.restaurant_id
    JOIN orders o ON oi.order_id = o.order_id
    WHERE o.order_status <> 'CANCELLED'
    GROUP BY m.item_id, m.name, r.name
)
SELECT item_id, item_name, restaurant_name, units_sold, sales_rank
FROM item_sales
WHERE sales_rank <= 3
ORDER BY sales_rank, item_name;

-- 26. Identify customers who have used promotional coupons
SELECT DISTINCT c.customer_id, c.full_name, c.email
FROM customers c
JOIN coupon_redemptions cr ON c.customer_id = cr.customer_id
ORDER BY c.customer_id;

-- 27. Find restaurants that have not received any orders
SELECT r.restaurant_id, r.name AS restaurant_name, r.city
FROM restaurants r
LEFT JOIN orders o ON r.restaurant_id = o.restaurant_id
WHERE o.order_id IS NULL
ORDER BY r.restaurant_id;

-- 28. Generate monthly restaurant revenue reports
SELECT DATE_FORMAT(o.order_date, '%Y-%m') AS revenue_month,
       r.restaurant_id,
       r.name AS restaurant_name,
       COUNT(o.order_id) AS total_orders,
       SUM(o.final_amount) AS monthly_revenue
FROM orders o
JOIN restaurants r ON o.restaurant_id = r.restaurant_id
WHERE o.order_status <> 'CANCELLED'
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m'), r.restaurant_id, r.name
ORDER BY revenue_month DESC, monthly_revenue DESC;

-- 29. Find delivery partners with the highest number of completed deliveries
WITH partner_counts AS (
    SELECT dp.partner_id, dp.full_name, dp.phone,
           COUNT(d.delivery_id) AS completed_deliveries,
           DENSE_RANK() OVER (ORDER BY COUNT(d.delivery_id) DESC) AS delivery_rank
    FROM delivery_partners dp
    JOIN deliveries d ON dp.partner_id = d.partner_id
    WHERE d.delivery_status = 'DELIVERED'
    GROUP BY dp.partner_id, dp.full_name, dp.phone
)
SELECT partner_id, full_name, phone, completed_deliveries
FROM partner_counts
WHERE delivery_rank = 1;

-- 30. Identify customers who have placed orders but have never submitted a review
SELECT DISTINCT c.customer_id, c.full_name, c.email
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
LEFT JOIN reviews rev ON c.customer_id = rev.customer_id
WHERE rev.review_id IS NULL
ORDER BY c.customer_id;