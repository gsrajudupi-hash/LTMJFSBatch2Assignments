-- Question 28 Generate monthly restaurant revenue reports.
 
SELECT
    r.restaurant_id,
    r.restaurant_name,
    YEAR(o.order_date) AS order_year,
    MONTH(o.order_date) AS order_month,
    SUM(o.total_amount) AS monthly_revenue
FROM restaurants r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
