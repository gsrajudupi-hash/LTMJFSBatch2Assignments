-- Question 17. Display delivery partners who have completed more than five deliveries.
SELECT
    dp.partner_id,
    dp.partner_name,
    COUNT(d.delivery_id) AS completed_deliveries
FROM delivery_partners dp
INNER JOIN deliveries d
    ON dp.partner_id = d.partner_id
WHERE d.delivery_status = 'DELIVERED'
GROUP BY
    dp.partner_id,
    dp.partner_name
HAVING COUNT(d.delivery_id) > 5;

