-- Question 15. Find the most frequently ordered food item.
-- Concept: JOIN, SUM() and ORDER BY
SELECT
    m.menu_item_id,
    m.item_name,
    SUM(oi.quantity) AS total_quantity_ordered
FROM order_items oi
INNER JOIN menu_items m
    ON oi.menu_item_id = m.menu_item_id
GROUP BY
    m.menu_item_id,
    m.item_name
ORDER BY total_quantity_ordered DESC
LIMIT 1;

