    m.price
FROM menu_item m
LEFT JOIN order_item oi
    ON m.menu_item_id = oi.menu_item_id
WHERE oi.order_item_id IS NULL;

-- 25. Find the top three best-selling food items

SELECT
    m.menu_item_id,
    m.name,
    SUM(oi.quantity) AS total_quantity_sold
FROM menu_item m
JOIN order_item oi
    ON m.menu_item_id = oi.menu_item_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status <> 'CANCELLED'
GROUP BY m.menu_item_id, m.name
ORDER BY total_quantity_sold DESC
LIMIT 3;


-- 26. Identify customers who have used--  promotional coupons
SELECT DISTINCT
    c.customer_id,
    c.name,
    c.email,
    cp.code AS coupon_code
FROM customer c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN coupon_redemption cr
    ON o.order_id = cr.order_id
JOIN coupon cp
    ON cr.coupon_id = cp.coupon_id;
    
--  27. Find restaurants that have not received any orders
SELECT
    r.restaurant_id,
    r.name AS restaurant_name
FROM restaurant r
LEFT JOIN orders o
    ON r.restaurant_id = o.restaurant_id
WHERE o.order_id IS NULL;

-- 28. Generate monthly restaurant revenue reports
SELECT
    r.restaurant_id,
    r.name AS restaurant_name,
    YEAR(o.ordered_at) AS year,
    MONTH(o.ordered_at) AS month,
    SUM(o.final_amount) AS total_revenue
FROM restaurant r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
WHERE o.status = 'DELIVERED'
GROUP BY
    r.restaurant_id,
    r.name,
    YEAR(o.ordered_at),
    MONTH(o.ordered_at)
ORDER BY
    year,
    month,
    r.restaurant_id;


-- 29. Find delivery partners with the highest number of completed deliveries
WITH delivery_counts AS (
    SELECT
        dp.partner_id,
        dp.name,
        COUNT(da.assignment_id) AS completed_deliveries
    FROM delivery_partner dp
    JOIN delivery_assignment da
        ON dp.partner_id = da.partner_id
    WHERE da.delivery_status = 'DELIVERED'
    GROUP BY dp.partner_id, dp.name
)
SELECT *
FROM delivery_counts
WHERE completed_deliveries = (
    SELECT MAX(completed_deliveries)
    FROM delivery_counts
);

-- 30. Identify customers who have placed orders but have never submitted a review
SELECT
    c.customer_id,
    c.name,
    c.email
FROM customer c
WHERE EXISTS (
    SELECT 1
    FROM orders o
    WHERE o.customer_id = c.customer_id
)
AND NOT EXISTS (
    SELECT 1
    FROM orders o
    JOIN review r
        ON o.order_id = r.order_id
    WHERE o.customer_id = c.customer_id
);
