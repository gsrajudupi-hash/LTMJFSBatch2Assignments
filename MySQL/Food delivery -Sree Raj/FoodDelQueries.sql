-- 21. Find the second most expensive food item
SELECT
    menu_item_id,
    name AS food_item,
    price
FROM menu_item
WHERE price = (
    SELECT MAX(price)
    FROM menu_item
    WHERE price < (
        SELECT MAX(price)
        FROM menu_item
    )
);

-- 22. Find restaurants whose average ratings are greater than the overall average rating
SELECT
    r.restaurant_id,
    r.name AS restaurant_name,
    AVG(rv.rating) AS average_rating
FROM restaurant r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
JOIN review rv
    ON o.order_id = rv.order_id
WHERE rv.menu_item_id IS NULL
GROUP BY r.restaurant_id, r.name
HAVING AVG(rv.rating) > (
    SELECT AVG(rating)
    FROM review
    WHERE menu_item_id IS NULL
);

-- 23. Find customers who have placed more orders than the average number of orders per customer
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS total_orders
FROM customer c
JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.name
HAVING COUNT(o.order_id) > (
    SELECT AVG(order_count)
    FROM (
        SELECT COUNT(*) AS order_count
        FROM orders
        GROUP BY customer_id
    ) AS customer_orders
);


-- 24. Find food items that have never been ordered
SELECT
