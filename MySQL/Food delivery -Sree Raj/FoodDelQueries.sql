-- Basic LEVEL

-- 1. Display all registered customers.
SELECT * FROM customers;

-- 2. Display all active restaurants.
SELECT * FROM restaurant WHERE is_active = TRUE;

-- 3. Find all vegetarian food items.
SELECT *
FROM menu_item WHERE is_vegetarian = TRUE;

-- 4. Display food items belonging to a particular restaurant.
SELECT * food FROM menu_item WHERE restaurant_id = 1;

-- 5. Find food items whose price is greater than 200.
SELECT * FROM menu_item WHERE price>200

-- 6. Display all orders placed by a particular customer.
SELECT * FROM orders WHERE customer_id = 1;

-- 7. Find all orders placed on a particular date.
SELECT * FROM orders WHERE DATE(ordered_at) = '2026-11-15';

-- 8. Display all available delivery partners
SELECT * FROM delivery_partner WHERE availability_status= 'AVAILABLE';


-- Intermediate Level

-- 9. Display customer details along with their delivery addresses.
SELECT * FROM customer c 
JOIN customer_address ca ON c.customer_id = ca.customer_id;

-- 10. Display restaurant names along with their food menu.
SELECT r.restaurant_id, r.name AS restaurant_name, m.name AS food_item,
 m.description, m.price, m.is_vegetarian, m.is_available
FROM restaurant r
JOIN menu_item m ON r.restaurant_id = m.restaurant_id;

-- 11. Display complete order details, including customer and restaurant information.
SELECT o.order_id, o.ordered_at, o.status,o.subtotal, o.delivery_charge, o.discount,
o.final_amount,o.estimated_delivery_at,c.customer_id,c.name AS customer_name,
c.email AS customer_email,c.mobile_number,r.restaurant_id,r.name AS restaurant_name,
r.address AS restaurant_address,r.contact_number
FROM orders o 
JOIN customer c ON o.customer_id = c.customer_id
JOIN restaurant r ON o.restaurant_id = r.restaurant_id;F

-- 12. Find the total number of orders placed by each customer.
SELECT c.customer_id, c.name, COUNT(o.order_id) AS total_orders
FROM customer c LEFT JOIN orders o ON 
c.customer_id=o.customer_id
GROUP BY c.customer_id , c.name;


-- 13. Find the total number of food items available in each restaurant.
SELECT r.restaurant_id, r.name AS restaurant_name
COUNT(m.menu_item_id) AS total_food_items
FROM restaurant r LEFT JOIN menu_item m ON r.restaurant_id=m.restaurant_id
AND m.is_available = TRUE
GROUP BY r.restaurant_id, r,name

-- 14. Calculate the total sales generated by each restaurant.
SELECT
    r.restaurant_id,
    r.name AS restaurant_name,
    SUM(o.final_amount) AS total_sales
FROM restaurant r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
WHERE o.status = 'DELIVERED'
GROUP BY r.restaurant_id, r.name;

-- 15. Find the most frequently ordered food item. 
SELECT
    m.menu_item_id,
    m.name AS food_item,
    SUM(oi.quantity) AS total_quantity_ordered
FROM menu_item m
JOIN order_item oi
    ON m.menu_item_id = oi.menu_item_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status <> 'CANCELLED'
GROUP BY m.menu_item_id, m.name
ORDER BY total_quantity_ordered DESC
LIMIT 1;

-- 16. Find customers who have never placed an order.
SELECT * FROM customer c LEFT JOIN orders o ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL


 -- 17. Display delivery partners who have completed more than five deliveries
 SELECT
    dp.partner_id,
    dp.name,
    COUNT(da.assignment_id) AS completed_deliveries
FROM delivery_partner dp
JOIN delivery_assignment da
    ON dp.partner_id = da.partner_id
WHERE da.delivery_status = 'DELIVERED'
GROUP BY dp.partner_id, dp.name
HAVING COUNT(da.assignment_id) > 5;

-- 18. Find the average rating of each restaurant.
SELECT
    r.restaurant_id,
    r.name AS restaurant_name,
    AVG(rv.rating) AS average_rating
FROM restaurant r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
JOIN review rv
    ON o.order_id = rv.order_id
WHERE rv.menu_item_id IS NULL
GROUP BY r.restaurant_id, r.name;


-- Advanced level

-- 19. Find the customer who has spent the highest amount on food orders
SELECT
    c.customer_id,
    c.name,
    SUM(o.final_amount) AS total_amount_spent
FROM customer c
JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.status = 'DELIVERED'
GROUP BY c.customer_id, c.name
ORDER BY total_amount_spent DESC
LIMIT 1;

-- 20. Find the restaurant that generated the highest revenue
SELECT
