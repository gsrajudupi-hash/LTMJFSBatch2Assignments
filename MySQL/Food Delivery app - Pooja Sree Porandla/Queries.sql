-- Display ALL customers 
SELECT * FROM customers;
-- 2. Display all active restaurants
SELECT *
FROM restaurants
WHERE is_active = TRUE;


-- 3. Find all vegetarian food items
SELECT *
FROM menu_items
WHERE food_type = 'VEG';


-- 4. Food items belonging to a particular restaurant
SELECT mi.*
FROM menu_items mi
JOIN restaurants r
    ON r.restaurant_id = mi.restaurant_id
WHERE r.restaurant_id = 1;


-- 5. Food items whose price is greater than ₹200
SELECT item_id, item_name, price
FROM menu_items
WHERE price > 200;


-- 6. Orders placed by a particular customer
SELECT *
FROM orders
WHERE customer_id = 1
ORDER BY order_date DESC;


-- 7. Orders placed on a particular date
SELECT *
FROM orders
WHERE order_date >= '2026-11-01'
  AND order_date < '2026-11-02';


-- 8. Available delivery partners
SELECT *
FROM delivery_partners
WHERE is_available = TRUE;


-- 9. Customer details with delivery addresses
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    c.mobile_number,
    a.address_type,
    a.house_number,
    a.street,
    a.city,
    a.state,
    a.pincode
FROM customers c
LEFT JOIN customer_addresses a
    ON a.customer_id = c.customer_id;


-- 10. Restaurant names with food menu
SELECT
    r.restaurant_name,
    mi.item_name,
    mi.price,
    mi.food_type,
    mi.is_available
FROM restaurants r
LEFT JOIN menu_items mi
    ON mi.restaurant_id = r.restaurant_id;


-- 11. Complete order details with customer and restaurant
SELECT
    o.order_id,
    o.order_date,
    o.order_status,
    o.total_amount,
    c.first_name,
    c.last_name,
    r.restaurant_name,
    mi.item_name,
    oi.quantity,
    oi.item_price,
    oi.total_price
FROM orders o
JOIN customers c
    ON c.customer_id = o.customer_id
JOIN restaurants r
    ON r.restaurant_id = o.restaurant_id
JOIN order_items oi
    ON oi.order_id = o.order_id
JOIN menu_items mi
    ON mi.item_id = oi.item_id;


-- 12. Total orders placed by each customer
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o
    ON o.customer_id = c.customer_id
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name;


-- 13. Number of available food items in each restaurant
SELECT
    r.restaurant_id,
    r.restaurant_name,
    COUNT(mi.item_id) AS available_items
FROM restaurants r
LEFT JOIN menu_items mi
    ON mi.restaurant_id = r.restaurant_id
    AND mi.is_available = TRUE
GROUP BY
    r.restaurant_id,
    r.restaurant_name;


-- 14. Total sales generated by each restaurant
SELECT
    r.restaurant_id,
    r.restaurant_name,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM restaurants r
LEFT JOIN orders o
    ON o.restaurant_id = r.restaurant_id
GROUP BY
    r.restaurant_id,
    r.restaurant_name;


-- 15. Most frequently ordered food item
SELECT
    mi.item_id,
    mi.item_name,
    SUM(oi.quantity) AS total_quantity
FROM menu_items mi
JOIN order_items oi
    ON oi.item_id = mi.item_id
JOIN orders o
    ON o.order_id = oi.order_id
GROUP BY
    mi.item_id,
    mi.item_name
ORDER BY total_quantity DESC
LIMIT 1;


-- 16. Customers who have never placed an order
SELECT c.*
FROM customers c
LEFT JOIN orders o
    ON o.customer_id = c.customer_id
WHERE o.order_id IS NULL;


-- 17. Delivery partners with more than five completed deliveries
SELECT
    dp.partner_id,
    dp.partner_name,
    COUNT(d.delivery_id) AS completed_deliveries
FROM delivery_partners dp
JOIN deliveries d
    ON d.partner_id = dp.partner_id
WHERE d.delivery_status = 'COMPLETED'
GROUP BY
    dp.partner_id,
    dp.partner_name
HAVING COUNT(d.delivery_id) > 5;


-- 18. Average rating of each restaurant
SELECT
    r.restaurant_id,
    r.restaurant_name,
    ROUND(AVG(rv.rating), 2) AS average_rating
FROM restaurants r
LEFT JOIN reviews rv
    ON rv.restaurant_id = r.restaurant_id
GROUP BY
    r.restaurant_id,
    r.restaurant_name;


-- 19. Customer who spent the highest amount on food orders
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    SUM(o.total_amount) AS total_spent
FROM customers c
JOIN orders o
    ON o.customer_id = c.customer_id
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
ORDER BY total_spent DESC
LIMIT 1;


-- 20. Restaurant with highest revenue
SELECT
    r.restaurant_id,
    r.restaurant_name,
    SUM(o.total_amount) AS revenue
FROM restaurants r
JOIN orders o
    ON o.restaurant_id = r.restaurant_id
GROUP BY
    r.restaurant_id,
    r.restaurant_name
ORDER BY revenue DESC
LIMIT 1;


-- 21. Second most expensive food item (second distinct price)
SELECT
    item_id,
    item_name,
    price
FROM menu_items
WHERE price = (
    SELECT MAX(price)
    FROM menu_items
    WHERE price < (
        SELECT MAX(price)
        FROM menu_items
    )
);


-- 22. Restaurants with average rating above overall average
SELECT
    r.restaurant_id,
    r.restaurant_name,
    AVG(rv.rating) AS avg_rating
FROM restaurants r
JOIN reviews rv
    ON rv.restaurant_id = r.restaurant_id
GROUP BY
    r.restaurant_id,
    r.restaurant_name
HAVING AVG(rv.rating) > (
    SELECT AVG(rating)
    FROM reviews
);


-- 23. Customers with more orders than average customer order count
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(o.order_id) AS order_count
FROM customers c
LEFT JOIN orders o
    ON o.customer_id = c.customer_id
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
HAVING COUNT(o.order_id) > (
    SELECT AVG(order_count)
    FROM (
        SELECT COUNT(*) AS order_count
        FROM orders
        GROUP BY customer_id
    ) customer_orders
);