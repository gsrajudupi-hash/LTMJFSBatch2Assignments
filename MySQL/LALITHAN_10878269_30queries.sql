-- 29. Find delivery partners with the highest number
--     of completed deliveries.

WITH delivery_counts AS (
    SELECT
        dp.delivery_partner_id,
        dp.partner_name,
        COUNT(d.delivery_id) AS completed_deliveries
    FROM delivery_partner dp
    LEFT JOIN delivery d
        ON dp.delivery_partner_id = d.delivery_partner_id
        AND d.delivery_status = 'DELIVERED'
    GROUP BY
        dp.delivery_partner_id,
        dp.partner_name
)
SELECT
    delivery_partner_id,
    partner_name,
    completed_deliveries
FROM delivery_counts
WHERE completed_deliveries = (
    SELECT MAX(completed_deliveries)
    FROM delivery_counts
);


