-- 28. Generate monthly restaurant revenue reports.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,

    YEAR(co.orderTime) AS revenueYear,
    MONTH(co.orderTime) AS revenueMonth,
    MONTHNAME(co.orderTime) AS monthName,

    COUNT(co.orderId) AS deliveredOrders,

    SUM(co.subtotal) AS foodSubtotal,
    SUM(co.deliveryCharge) AS deliveryCharges,
    SUM(co.discountAmt) AS discountsGiven,
    SUM(co.totalAmt) AS totalRevenue

FROM restaurant r

INNER JOIN customerOrder co
    ON r.restaurantId = co.restaurantId

WHERE co.orderStatus = 'DELIVERED'

GROUP BY
    r.restaurantId,
    r.ownerName,
    YEAR(co.orderTime),
    MONTH(co.orderTime),
    MONTHNAME(co.orderTime)

ORDER BY
    revenueYear,
    revenueMonth,
    totalRevenue DESC;


