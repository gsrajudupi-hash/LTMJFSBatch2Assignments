-- 22. Find restaurants with above-average ratings.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,

    ROUND(AVG(rv.rating), 2) AS restaurantAverageRating

FROM restaurant r

INNER JOIN review rv
    ON r.restaurantId = rv.restaurantId

WHERE rv.menuItemId IS NULL

GROUP BY
    r.restaurantId,
    r.ownerName

HAVING AVG(rv.rating) > (

    SELECT AVG(rating)
    FROM review
    WHERE menuItemId IS NULL

)

ORDER BY restaurantAverageRating DESC;


-- 23. Find customers who placed more orders than average.
WITH customer_order_counts AS (

    SELECT
        c.customer_id,
        c.firstName,
        c.lastName,
        c.email,

        COUNT(co.orderId) AS totalOrders

    FROM customer c

    LEFT JOIN customerOrder co
        ON c.customer_id = co.customerId

    GROUP BY
        c.customer_id,
        c.firstName,
        c.lastName,
        c.email
)

SELECT
    customer_id,

    CONCAT(
        firstName,
        ' ',
        lastName
    ) AS customerName,

    email,
    totalOrders

FROM customer_order_counts

WHERE totalOrders > (

    SELECT AVG(totalOrders)
    FROM customer_order_counts

)

ORDER BY totalOrders DESC;


