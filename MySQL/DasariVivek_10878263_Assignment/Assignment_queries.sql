SELECT *
FROM customerOrder
WHERE customerId = 1;


-- 7. Find all orders placed on a particular date.
SELECT *
FROM customerOrder
WHERE DATE(orderTime) = '2026-11-10';


-- 8. Display all available delivery partners.
SELECT *
FROM deliveryPartner
WHERE availabilityStatus = 'AVAILABLE';


-- 9. Display customer details along with their delivery addresses.
SELECT
    c.customer_id,
    c.firstName,
    c.lastName,
    c.email,
    c.phoneNum,
    c.status,
    ca.addressId,
    ca.label,
    ca.addressLine1,
    ca.addressLine2,
    ca.city,
    ca.state,
    ca.pincode,
    ca.is_default
FROM customer c
INNER JOIN customerAddress ca
    ON c.customer_id = ca.customerId
ORDER BY
    c.customer_id,
    ca.is_default DESC;


-- 10. Display restaurant names along with their food menu.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,
    fc.categoryName,
    mi.menuItemId,
    mi.itemName,
    mi.description,
    mi.price,
    mi.foodType,
    mi.is_available
FROM restaurant r
INNER JOIN menuItem mi
    ON r.restaurantId = mi.restaurantId
INNER JOIN foodCategory fc
    ON mi.categoryId = fc.categoryId
ORDER BY
    r.ownerName,
    fc.categoryName,
    mi.itemName;


-- 11. Display complete order details.
SELECT
    co.orderId,
    co.orderTime,
    co.orderStatus,
    co.restaurantDecision,

    c.customer_id,
    CONCAT(c.firstName, ' ', c.lastName) AS customerName,
    c.email AS customerEmail,
    c.phoneNum AS customerPhone,

    r.restaurantId,
    r.ownerName AS restaurantName,
    r.email AS restaurantEmail,
    r.phoneNum AS restaurantPhone,

    ca.addressLine1,
    ca.addressLine2,
    ca.city,
    ca.state,
    ca.pincode,

    oi.itemName,
    oi.quantity,
    oi.unitPrice,

    (oi.quantity * oi.unitPrice) AS totalPrice,

    co.subtotal,
    co.deliveryCharge,
    co.discountAmt,
    co.totalAmt,
    co.specialInstructions

FROM customerOrder co

INNER JOIN customer c
    ON co.customerId = c.customer_id

INNER JOIN restaurant r
    ON co.restaurantId = r.restaurantId

INNER JOIN customerAddress ca
    ON co.addressId = ca.addressId

INNER JOIN orderItem oi
    ON co.orderId = oi.orderId

ORDER BY
    co.orderTime DESC,
    co.orderId,
    oi.orderItemId;


-- 12. Find total number of orders placed by each customer.
SELECT
    c.customer_id,
    CONCAT(c.firstName, ' ', c.lastName) AS customerName,
    COUNT(co.orderId) AS totalOrders

FROM customer c

LEFT JOIN customerOrder co
    ON c.customer_id = co.customerId

GROUP BY
    c.customer_id,
    c.firstName,
    c.lastName

ORDER BY
    totalOrders DESC,
    customerName;


-- 13. Find total available food items in each restaurant.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,
    COUNT(mi.menuItemId) AS availableFoodItems

FROM restaurant r

LEFT JOIN menuItem mi
    ON r.restaurantId = mi.restaurantId
    AND mi.is_available = TRUE

GROUP BY
    r.restaurantId,
    r.ownerName

ORDER BY
    availableFoodItems DESC,
    restaurantName;


-- 14. Calculate total sales generated by each restaurant.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,
    COALESCE(SUM(co.totalAmt), 0) AS totalSales

FROM restaurant r

LEFT JOIN customerOrder co
    ON r.restaurantId = co.restaurantId
    AND co.orderStatus = 'DELIVERED'

GROUP BY
    r.restaurantId,
    r.ownerName

ORDER BY totalSales DESC;


-- 15. Find most frequently ordered food item.
SELECT
    oi.menuItemId,
    oi.itemName,
    SUM(oi.quantity) AS totalQuantityOrdered

FROM orderItem oi

INNER JOIN customerOrder co
    ON oi.orderId = co.orderId

WHERE co.orderStatus <> 'CANCELLED'

GROUP BY
    oi.menuItemId,
    oi.itemName

ORDER BY totalQuantityOrdered DESC

LIMIT 1;


