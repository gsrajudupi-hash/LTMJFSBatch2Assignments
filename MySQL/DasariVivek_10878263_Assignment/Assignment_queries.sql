-- 30. Find customers who ordered but never submitted reviews.
SELECT
    c.customer_id,
    c.firstName,
    c.lastName,
    c.email,
    c.phoneNum

FROM customer c

WHERE EXISTS (

    SELECT 1
    FROM customerOrder co
    WHERE co.customerId = c.customer_id

)

AND NOT EXISTS (

    SELECT 1
    FROM review rv
    WHERE rv.customerId = c.customer_id

)

ORDER BY
    c.firstName,
    c.lastName;