-- 17. Find delivery partners with more than five completed deliveries.
SELECT
    dp.partnerId,

    CONCAT(
        dp.partnerFirstName,
        ' ',
        dp.partnerLastName
    ) AS partnerName,

    dp.mobile,
    dp.vehicleNumber,
    dp.vehicleType,

    COUNT(d.deliveryId) AS completedDeliveries

FROM deliveryPartner dp

INNER JOIN delivery d
    ON dp.partnerId = d.partnerId

WHERE d.deliveryStatus = 'DELIVERED'

GROUP BY
    dp.partnerId,
    dp.partnerFirstName,
    dp.partnerLastName,
    dp.mobile,
    dp.vehicleNumber,
    dp.vehicleType

HAVING COUNT(d.deliveryId) > 5

ORDER BY completedDeliveries DESC;


-- 18. Find average rating of each restaurant.
SELECT
    r.restaurantId,
    r.ownerName AS restaurantName,

    ROUND(AVG(rv.rating), 2) AS averageRating,

    COUNT(rv.reviewId) AS totalReviews

FROM restaurant r

LEFT JOIN review rv
    ON r.restaurantId = rv.restaurantId
    AND rv.menuItemId IS NULL

GROUP BY
    r.restaurantId,
    r.ownerName

ORDER BY
    averageRating DESC,
    totalReviews DESC;


